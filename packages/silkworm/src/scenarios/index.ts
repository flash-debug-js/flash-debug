import type { DebugContentFormat, DebugLogLevel, DebugLogRecord, DebugLogSource, DebugLogType } from '@flash-debug/types'
import type { SeededRandom } from '../runner/random'
import type { GeneratedLog, SilkwormScenario } from '../runner/types'

export interface ScenarioContext {
  id: string
  timestamp: string
  sequence: number
  clientId: string
  deviceId: string
  scenario: SilkwormScenario
  random: SeededRandom
}

const levels: readonly DebugLogLevel[] = ['debug', 'info', 'warning', 'error']
const types: readonly DebugLogType[] = [
  'log',
  'network',
  'exception',
  'performance',
  'event',
]
const sources: readonly DebugLogSource[] = ['flutter', 'adb', 'server']
const formats: readonly DebugContentFormat[] = [
  'json',
  'jsonl',
  'yaml',
  'ansi',
  'text',
]

function baseRecord(context: ScenarioContext, overrides: Partial<DebugLogRecord> = {}): DebugLogRecord {
  return {
    id: context.id,
    timestamp: context.timestamp,
    level: 'info',
    type: 'log',
    source: 'flutter',
    deviceId: context.deviceId,
    message: `silkworm event ${context.sequence}`,
    content: `Generated by ${context.scenario}`,
    contentFormat: 'text',
    ...overrides,
  }
}

function contentFor(format: DebugContentFormat, context: ScenarioContext): string {
  if (format === 'json') {
    return JSON.stringify({
      requestId: `req-${context.sequence}`,
      ok: context.random.bool(0.8),
      durationMs: context.random.int(2, 680),
    }, null, 2)
  }
  if (format === 'jsonl') {
    return JSON.stringify({ event: 'response', sequence: context.sequence, ok: true })
  }
  if (format === 'yaml') {
    return `requestId: req-${context.sequence}\nok: true\ndurationMs: ${context.random.int(2, 680)}`
  }
  if (format === 'ansi') {
    return '\u001B[32m[200]\u001B[0m GET /api/health 18ms'
  }
  return `A plain text payload produced by Silkworm at sequence ${context.sequence}.`
}

function buildRecord(context: ScenarioContext, overrides: Partial<DebugLogRecord> = {}): DebugLogRecord {
  const level = overrides.level ?? context.random.pick(levels)
  const type = overrides.type ?? context.random.pick(types)
  const format = overrides.contentFormat ?? context.random.pick(formats)
  return baseRecord(context, {
    level,
    type,
    contentFormat: format,
    content: contentFor(format, context),
    message: `${type} event from ${overrides.source ?? 'flutter'}`,
    ...overrides,
  })
}

export function createScenarioRecord(context: ScenarioContext): GeneratedLog {
  switch (context.scenario) {
    case 'normal':
      return buildRecord(context, {
        level: context.random.pick([
          'debug',
          'info',
          'info',
          'warning',
          'error',
        ]),
        type: 'log',
        source: 'flutter',
        contentFormat: 'text',
        message: context.random.pick([
          'screen mounted',
          'button pressed',
          'cache refreshed',
          'request completed',
        ]),
        content: `Flutter debug message ${context.sequence}`,
      })
    case 'mixed-sources':
      return buildRecord(context, {
        source: context.random.pick(sources),
        tag: context.random.pick(['App', 'Network', 'ADB', 'Router']),
      })
    case 'content-formats': {
      const contentFormat = context.random.pick(formats)
      return buildRecord(context, {
        contentFormat,
        content: contentFor(contentFormat, context),
      })
    }
    case 'network':
      return buildRecord(context, {
        type: 'network',
        level: context.random.bool(0.82)
          ? 'info'
          : 'error',
        contentFormat: 'json',
        message: context.random.pick(['GET /api/health', 'POST /api/v1/logs/batch', 'GET /users/me']),
        attributes: {
          method: context.random.pick(['GET', 'POST', 'PUT']),
          statusCode: context.random.bool(0.85)
            ? 200
            : context.random.pick([400, 429, 500]),
          durationMs: context.random.int(2, 680),
        },
      })
    case 'exceptions':
      return buildRecord(context, {
        type: 'exception',
        level: 'error',
        contentFormat: 'text',
        message: context.random.pick(['Unhandled exception', 'TimeoutException', 'StateError']),
        error: context.random.pick(['TimeoutException: request timed out', 'StateError: invalid state', 'Error: failed to decode response']),
        stackTrace: 'at SilkwormScenario.generate (scenario.ts:42:11)\nat Logger.send (logger.ts:18:5)',
      })
    case 'burst':
      return buildRecord(context, {
        type: 'event',
        level: 'info',
        contentFormat: 'jsonl',
        message: `burst event ${context.sequence}`,
      })
    case 'duplicates':
      return buildRecord(context, {
        id: `${context.clientId}-duplicate-${context.sequence % 3}`,
        type: 'event',
        level: 'info',
        contentFormat: 'json',
      })
    case 'invalid':
      if (context.sequence % 3 === 0) {
        return { timestamp: context.timestamp, message: 'missing id and required fields' }
      }
      if (context.sequence % 3 === 1) {
        return {
          id: context.id,
          timestamp: context.timestamp,
          level: 'unknown',
          type: 'unknown',
          message: '',
        }
      }
      return {
        id: context.id,
        timestamp: context.timestamp,
        message: 'oversized payload',
        content: 'x'.repeat(4096),
      }
    case 'multi-device':
      return buildRecord(context, {
        deviceId: `pixel-${context.random.int(5, 9)}`,
        source: context.random.pick(['flutter', 'adb']),
      })
    case 'long-run':
      return buildRecord(context, {
        level: context.random.pick(['debug', 'info', 'info']),
        type: 'performance',
        contentFormat: 'text',
        message: 'heartbeat',
        content: `Long run heartbeat ${context.sequence}`,
      })
  }
}
